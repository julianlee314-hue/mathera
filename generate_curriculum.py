def make_skills(era_roman, domain_idx, titles, starter_n=2):
    out = []
    for i, title in enumerate(titles, 1):
        sid = f"{era_roman}.{domain_idx}.{i:02d}"
        if i <= starter_n:
            state = "seed" if i > 1 else "growing"
            was = "seed" if i == 1 else None
        else:
            state = "inferred"
            was = None
        sk = {
            "id": sid,
            "title": title,
            "star": False,
            "was": was,
            "steps": ["a", "b", "c", "d"],
            "state": state,
        }
        if state == "growing":
            sk["step"] = "b"
        out.append(sk)
    return out

def pad(titles, n, prefix):
    titles = list(titles)
    i = len(titles) + 1
    while len(titles) < n:
        titles.append(f"{prefix} · skill {i}")
        i += 1
    return titles[:n]

