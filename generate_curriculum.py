def era_block(era_id, name, roman, metaphor, tagline, unlock, domains_spec, roman_str):
    domains = []
    total = 0
    for di, (dname, titles) in enumerate(domains_spec, 1):
        skills = make_skills(roman_str, di, titles, starter_n=2 if unlock else 0)
        # For locked-ish early eras with unlock True, first domain gets growing
        domains.append({
            "id": f"{roman_str}.{di}",
            "name": dname,
            "skills": skills,
        })
        total += len(skills)
    return {
        "id": era_id,
        "name": name,
        "roman": roman,
        "romanLabel": roman_str,
        "unlock": unlock,
        "metaphor": metaphor,
        "tagline": tagline,
        "total": total,
        "domains": domains,
    }

def placeholders(era_id, name, roman, metaphor, tagline, unlock, branch_names, per=12):
    # 7 lightweight domains
    specs = []
    for i, bn in enumerate(branch_names):
        titles = [f"{bn} · {j:02d}" for j in range(1, per + 1)]
        # richer for Count first branch
        specs.append((bn, titles))
    return era_block(era_id, name, roman, metaphor, tagline, unlock, specs, ["I","II","III","IV","V","VI","VII"][roman])

